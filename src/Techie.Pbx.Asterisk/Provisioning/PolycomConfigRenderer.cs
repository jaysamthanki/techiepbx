using System.Globalization;
using System.Text;
using Techie.Pbx.Core.Models;

namespace Techie.Pbx.Asterisk.Provisioning
{
    /// <summary>
    /// One phone's configuration, generated from its row and the keys assigned to it. Pure
    /// function: data in, text out, no lookups and no I/O — the file is never written to disk, it
    /// is generated for each request and handed straight to the phone (D79).
    ///
    /// The keys are the whole of it (schema 020): the line keys become the <c>reg.N</c>
    /// registrations, in key order, and every other key becomes an attendant resource. So the keys
    /// the Buttons tab shows are the keys the handset has, in the same order, with no ninth line
    /// appearing from somewhere else.
    ///
    /// A phone with no line key still gets a valid file: the time and a provisioning poll, and no
    /// registration. That is what lets a phone auto-register itself, sit on a desk showing the
    /// right time, and start working the moment an admin assigns it an extension and it polls
    /// again (D78).
    /// </summary>
    public static class PolycomConfigRenderer
    {
        /// <summary>
        /// What kind of attendant resource an assigned key is. "automata" is the monitored line:
        /// the phone SUBSCRIBEs to the address (so the lamp follows its hint) and pressing the
        /// key dials it, with the long-press behaviours (pickup, transfer to it) that Polycom
        /// attaches to a monitored key. "normal" would be a plain speed dial with no lamp, which
        /// is not what a key is for here. Both kinds of key we render want exactly this — a
        /// parking slot is dialled to retrieve the call in it, the same gesture as dialling a
        /// colleague (D121).
        /// </summary>
        private const string AttendantType = "automata";

        /// <summary>
        /// Seconds the phone waits for another digit before dialling what it has, which is what
        /// every pattern in <see cref="PolycomDigitMap"/> that ends in <c>T</c> is waiting for. A
        /// user who does not want to wait presses <c>#</c>.
        /// </summary>
        private const int DigitMapTimeoutSeconds = 3;

        /// <summary>How long the phone's registration lasts before it renews, in seconds.</summary>
        private const int RegistrationExpiration = 3600;

        /// <summary>
        /// How often the phone comes back for its config, in seconds. A day: long enough not to be
        /// a load on the server, short enough that assigning an extension takes effect without
        /// anyone walking to the desk. Rebooting the phone is the impatient version.
        /// </summary>
        private const int ProvisioningPollSeconds = 86400;

        /// <summary>The transport the phone registers over, matching the UDP transport we render.</summary>
        private const string Transport = "UDPOnly";

        public static string Render(PolycomConfig config)
        {
            var phone = config.Phone;

            var phoneErrors = phone.Validate();
            if (phoneErrors.Count > 0)
                throw new InvalidOperationException($"Phone '{phone.Mac}' is invalid: {string.Join(" ", phoneErrors)}");

            var sb = new StringBuilder();
            var mac = PolycomXml.Value(phone.Mac, "mac");

            sb.Append(PolycomXml.Declaration).Append('\n');
            PolycomXml.Comment(sb, "", $"Generated by TNPBX for {mac} per request. Nothing is stored on disk; edit the phone in TNPBX.");
            sb.Append("<polycomConfig>\n");

            // The time, and coming back for this file again: the two things every phone gets,
            // whether or not anyone has told it which extension it is.
            PolycomXml.Element(sb, "  ", "tcpIpApp", new[]
            {
                PolycomXml.Attribute("tcpIpApp.sntp.address", config.SntpAddress, "sntp address"),
                PolycomXml.Constant("tcpIpApp.sntp.gmtOffset", Number(config.GmtOffsetSeconds)),
            });

            PolycomXml.Element(sb, "  ", "prov", new[]
            {
                PolycomXml.Constant("prov.polling.enabled", "1"),
                PolycomXml.Constant("prov.polling.mode", "rel"),
                PolycomXml.Constant("prov.polling.period", Number(ProvisioningPollSeconds)),
            });

            // Phone-level, not extension-level, so it goes out whether or not anyone has been
            // assigned yet. Unset means left out rather than written blank: a blank password is
            // worse than no opinion at all (D84).
            var deviceAuth = new List<(string Name, string Value)>();
            if (config.AdminPassword.Length > 0)
            {
                // The .set flag is what makes the phone apply the password: without it the value
                // is stored and the login stays on the factory default (D84).
                deviceAuth.Add(PolycomXml.Attribute("device.auth.localAdminPassword", config.AdminPassword, "device admin password"));
                deviceAuth.Add(PolycomXml.Constant("device.auth.localAdminPassword.set", "1"));
            }
            if (config.UserPassword.Length > 0)
            {
                deviceAuth.Add(PolycomXml.Attribute("device.auth.localUserPassword", config.UserPassword, "device user password"));
                deviceAuth.Add(PolycomXml.Constant("device.auth.localUserPassword.set", "1"));
            }

            // device.set is the master flag the Edge E admin guide requires before any of the
            // device.auth password parameters take effect — the per-parameter .set alone is not
            // enough, and a half-applied password leaves the phone's login on a value nobody
            // remembers (D84).
            if (deviceAuth.Count > 0)
            {
                deviceAuth.Insert(0, PolycomXml.Constant("device.set", "1"));
                PolycomXml.Element(sb, "  ", "device", deviceAuth);
            }

            // Opt the phone out of Poly Lens data collection so it stops asking at every boot
            // (PVOS 8.4's da.optIn; Undecided is what makes it prompt). One line, no choice
            // offered: a TNPBX phone has no business phoning Lens.
            PolycomXml.Element(sb, "  ", "da", new List<(string Name, string Value)>
            {
                PolycomXml.Constant("da.optIn", "OptedOut"),
            });

            var buttons = Validated(config.Buttons);
            var lines = PhoneButton.Lines(buttons);

            if (lines.Count == 0)
            {
                PolycomXml.Comment(sb, "  ", "No extension is assigned to this phone yet, so it is given no registration.");
                sb.Append("</polycomConfig>\n");

                return sb.ToString();
            }

            // Built from the extensions this system has, so that nothing is ever sent early:
            // a four-digit fixed pattern used to cut a ten-digit transfer target down to four
            // digits on a real handset (D124).
            PolycomXml.Element(sb, "  ", "dialplan", new[]
            {
                PolycomXml.Constant("dialplan.digitmap", PolycomDigitMap.For(config.Extensions)),
                PolycomXml.Constant("dialplan.digitmap.timeOut", Number(DigitMapTimeoutSeconds)),
            });

            // A port of its own per phone, so two phones behind one NAT cannot collide (D81).
            PolycomXml.Element(sb, "  ", "voIpProt", new[]
            {
                PolycomXml.Constant("voIpProt.SIP.local.port", Number(phone.LocalSipPort)),
            });

            // One registration per line key, in key order, each taking one line key on the handset.
            var registrations = new List<(string Name, string Value)>();

            for (var index = 0; index < lines.Count; index++)
            {
                var extension = LineExtension(config, lines[index]);
                var reg = $"reg.{Number(index + 1)}";

                registrations.Add(PolycomXml.Attribute($"{reg}.displayName", extension.Name, "display name"));
                registrations.Add(PolycomXml.Attribute($"{reg}.address", extension.Number, "address"));
                registrations.Add(PolycomXml.Attribute($"{reg}.auth.userId", extension.Number, "auth user"));
                registrations.Add(PolycomXml.Attribute($"{reg}.auth.password", extension.Secret, "auth password"));
                registrations.Add(PolycomXml.Attribute($"{reg}.server.1.address", config.ServerAddress, "server address"));
                registrations.Add(PolycomXml.Constant($"{reg}.server.1.port", Number(config.SipPort)));
                registrations.Add(PolycomXml.Constant($"{reg}.server.1.transport", Transport));
                registrations.Add(PolycomXml.Constant($"{reg}.server.1.expires", Number(RegistrationExpiration)));
                registrations.Add(PolycomXml.Constant($"{reg}.lineKeys", "1"));
            }

            PolycomXml.Element(sb, "  ", "reg", registrations);

            // The message waiting light, and a missed call list on the phone itself. The first
            // registration only: a second line is a second person's extension, and their messages
            // are not this phone's to light a lamp about.
            PolycomXml.Element(sb, "  ", "msg", new[]
            {
                PolycomXml.Attribute("msg.mwi.1.subscribe", lines[0].TargetValue, "mwi subscribe"),
            });

            PolycomXml.Element(sb, "  ", "call", new[]
            {
                PolycomXml.Constant("call.missedCallTracking.1.enabled", "1"),
            });

            AppendAttendant(sb, config, buttons.Where(b => !b.IsLine).ToList(), lines.Count);

            sb.Append("</polycomConfig>\n");

            return sb.ToString();
        }

        /// <summary>
        /// The keys that are not registrations, written as Polycom's attendant resource list
        /// (D121). Each resource is a lamp and a quick dial: the phone SUBSCRIBEs for the address
        /// in its own dialplan context and dials the same address when the key is pressed. An
        /// extension's lamp follows the <c>PJSIP/&lt;number&gt;</c> hint and a parking slot's
        /// follows <c>park:&lt;slot&gt;@parkedcalls</c>, but that is the dialplan's doing — from
        /// here both are a number in the internal context, which is why this writes both the same
        /// way.
        ///
        /// There is no <c>attendant.uri</c>: that names a server-side resource list, and the list
        /// here is the one this file carries. Nothing is written at all for a phone whose only keys
        /// are its lines, so the rest of its line keys stay whatever the handset does with them.
        ///
        /// <b>Key 6 on the form is key 6 on the handset</b> (D121 amended again). The resources land
        /// on the line keys left over after the registrations, in order, so the resource index for a
        /// key is its position less the number of lines — and every index from 1 up to the last
        /// assigned key is written, whether or not anything is on it. A key the admin left blank
        /// gets a resource with an empty address and no label or type, which the phone leaves
        /// unassigned: skipping it instead would shuffle every key after it up one, and the list
        /// cannot simply stop at the gap because a phone reads it until the first index it does not
        /// find.
        /// </summary>
        private static void AppendAttendant(StringBuilder sb, PolycomConfig config, List<PhoneButton> buttons, int lines)
        {
            if (buttons.Count == 0)
                return;

            // Which registration the subscriptions and the calls go out on: the first line, which
            // is the extension this phone's own user answers as.
            var attributes = new List<(string Name, string Value)>
            {
                PolycomXml.Constant("attendant.reg", "1"),
            };

            // The keys are in key order, so the last one is the furthest down the handset.
            var last = buttons[^1].Position - lines;

            for (var index = 1; index <= last; index++)
            {
                var resource = $"attendant.resourceList.{Number(index)}";
                var button = buttons.FirstOrDefault(b => b.Position - lines == index);

                if (button == null)
                {
                    // The FreePBX module's generated configs write all three attributes, empty,
                    // for a blank slot: a lone empty address is skipped by the phone and every
                    // key after the gap shuffles up one (D121).
                    attributes.Add(PolycomXml.Constant($"{resource}.address", ""));
                    attributes.Add(PolycomXml.Constant($"{resource}.label", ""));
                    attributes.Add(PolycomXml.Constant($"{resource}.type", ""));
                    continue;
                }

                attributes.Add(PolycomXml.Attribute($"{resource}.address", button.TargetValue, "attendant address"));
                attributes.Add(PolycomXml.Attribute($"{resource}.label", button.Label(config.Extensions, config.CallFlowControls), "attendant label"));
                attributes.Add(PolycomXml.Constant($"{resource}.type", AttendantType));
            }

            PolycomXml.Comment(sb, "  ", "Keys assigned in TNPBX: a lamp and a quick dial each. An extension's lamp");
            PolycomXml.Comment(sb, "  ", "follows its hint; a parking slot's is lit while a call is sitting in it.");
            PolycomXml.Element(sb, "  ", "attendant", attributes);
        }

        /// <summary>
        /// The extension a line key registers as. The caller has already reduced the keys to the
        /// ones that can work (<see cref="PhoneButton.Usable"/>), so a line naming an extension
        /// this renderer was not given is the caller's mistake and is refused rather than written
        /// as a registration with no password behind it.
        /// </summary>
        private static Extension LineExtension(PolycomConfig config, PhoneButton line)
        {
            var extension = config.Extensions.FirstOrDefault(e =>
                string.Equals(e.Number, line.TargetValue, StringComparison.Ordinal));

            if (extension == null)
                throw new InvalidOperationException($"Phone key {line.Position} registers as extension '{line.TargetValue}', which the renderer was not given.");

            var errors = extension.Validate();
            if (errors.Count > 0)
                throw new InvalidOperationException($"Extension '{extension.Number}' is invalid: {string.Join(" ", errors)}");

            return extension;
        }

        private static string Number(int value) => value.ToString(CultureInfo.InvariantCulture);

        /// <summary>
        /// The keys in key order, re-validated as the phone and the extensions are: a row that
        /// reached us another way must not become a key that dials somewhere else.
        /// </summary>
        private static List<PhoneButton> Validated(IEnumerable<PhoneButton> buttons)
        {
            var ordered = buttons.OrderBy(b => b.Position).ToList();

            foreach (var button in ordered)
            {
                var errors = button.Validate();
                if (errors.Count > 0)
                    throw new InvalidOperationException($"Phone key {button.Position} is invalid: {string.Join(" ", errors)}");
            }

            return ordered;
        }
    }
}
